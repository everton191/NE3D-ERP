const fs = require("node:fs");
const assert = require("node:assert");
const app = fs.readFileSync("app.js", "utf8");
const cash = fs.readFileSync("src/features/cash/cash-commands.js", "utf8");
const renderer = fs.readFileSync("src/features/cash/cash-renderer.js", "utf8");
const css = fs.readFileSync("styles/ui-v3/screens/finance.css", "utf8");
assert.ok(app.includes('data-ui-version="v3" data-ui3-screen="caixa"') || renderer.includes('data-ui-version="v3" data-ui3-screen="caixa"'), "Caixa deve usar a raiz V3.");
assert.ok(app.includes("function calcularTotaisCaixaPeriodo"), "Cálculo financeiro deve permanecer disponível.");
assert.ok(app.includes("function editarMovimentoCaixa") && app.includes("function removerMovimentoCaixa"), "Ações financeiras devem permanecer disponíveis.");
assert.match(app, /function\s+editarMovimentoCaixa[\s\S]{0,400}SimplificaCashCommands\.editMovement/, "Edição do Caixa deve delegar ao CashCommands.");
assert.match(app, /function\s+removerMovimentoCaixa[\s\S]{0,400}SimplificaCashCommands\.cancelMovement/, "Cancelamento do Caixa deve delegar ao CashCommands.");
assert.ok(app.includes("window.UiV3.Dialog") && app.includes("getUi3: () => window.UiV3"), "Diálogos do Caixa devem usar Dialog V3 via injeção.");
const editStart = cash.indexOf("async function editMovement");
const cancelStart = cash.indexOf("async function cancelMovement");
assert.ok(editStart >= 0 && cancelStart > editStart, "Fluxos de edição e cancelamento devem existir no CashCommands.");
const editFlow = cash.slice(editStart, cancelStart);
const cancelFlow = cash.slice(cancelStart);
assert.ok(editFlow.includes("ui.Dialog") && !editFlow.includes('getElementById("popup")'), "Edição do Caixa deve usar Dialog V3.");
assert.ok(cancelFlow.includes("ui.Dialog") && !cancelFlow.includes('getElementById("popup")'), "Cancelamento do Caixa deve usar Dialog V3.");
const confirmationFlow = app.slice(app.indexOf("function solicitarConfirmacaoAcao"), app.indexOf("function solicitarPlanoSuperadmin"));
assert.ok(confirmationFlow.includes("window.UiV3.Dialog") && confirmationFlow.includes("onClose"), "Confirmações financeiras em telas V3 devem usar o Dialog oficial.");
assert.ok(css.includes("repeat(var(--ui3-grid-columns)"), "Caixa deve consumir o grid oficial.");
console.log("UI V3 financeiro: Caixa, movimentações, pagamentos e fechamento validados.");
