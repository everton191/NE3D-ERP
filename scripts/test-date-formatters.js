"use strict";
const assert = require("node:assert/strict");
const formatters = require("../src/shared/date-formatters.js");
assert.equal(formatters.formatShort(""), "");
assert.equal(formatters.formatShort("invalida"), "invalida");
assert.equal(formatters.formatDateTime(""), "—");
assert.equal(formatters.formatDateTime("invalida"), "invalida");
assert.match(formatters.formatDateTime("2026-09-19T10:30:00Z"), /^\d{2}\/\d{2}\/2026, \d{2}:\d{2}$/);
assert.equal(formatters.formatRelative("", 0), "Atualizado agora");
assert.equal(formatters.formatRelative(1000, 59999), "Atualizado agora");
assert.equal(formatters.formatRelative(1000, 121000), "Atualizado há 2 min");
assert.equal(formatters.formatRelative(1000, 7201000), "Atualizado há 2 h");
assert.equal(formatters.formatDeadline(""), "");
assert.equal(formatters.formatDeadline("invalid"), "invalid");
assert.equal(formatters.formatDeadline("2026-09-19"), "19/09/2026");
assert.equal(formatters.formatDocumentNumber("pedido-42", new Date(2026, 0, 1), 9), "2026-000042");
assert.equal(formatters.formatDocumentNumber("", new Date(2026, 0, 1), 9), "2026-000009");
assert.equal(formatters.formatUpdatedAt(""), "Aguardando atualização");
assert.match(formatters.formatUpdatedAt("2026-09-19T10:30:00Z"), /^Atualizado às \d{2}:\d{2}$/);
console.log("Shared date formatters preserve the effective app.js formatting contract.");
