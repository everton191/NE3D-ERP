const assert = require("assert");
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const root = path.resolve(__dirname, "..");
function load(relative, context) { vm.runInContext(fs.readFileSync(path.join(root, relative), "utf8"), context, { filename: relative }); }
const manifest = JSON.parse(fs.readFileSync(path.join(root, "config/ai/model-manifest.json"), "utf8"));
const context = vm.createContext({ console, globalThis: {}, module: { exports: {} }, require: (id) => require(path.join(root, "src/ai", id.replace("./", ""))), JSON, Object, String, Array, Set, Map, Date });
context.globalThis = context;
load("src/ai/model-manifest.js", context);
assert.equal(context.SimplificaModelManifest.validateModelManifest(manifest).ok, true, "pinned manifest must validate");
const needle = manifest.models.find((model) => model.id === "needle3");
assert.equal(needle.revision, "b274efcb211a9eef48c9a88da4b43bd569696a39");
assert.equal(needle.expectedSize, 35335380);
assert.match(needle.sha256, /^[a-f0-9]{64}$/);
assert.equal(needle.destinationPath, "ai/models/needle3/needle3.cact");
const lfm = manifest.models.find((model) => model.id === "lfm2.5-1.2b-q4_0");
assert.equal(lfm.repo, "LiquidAI/LFM2.5-1.2B-Instruct-GGUF"); assert.equal(lfm.revision, "8ed288026e23958ad9dfa92d53ed773a8eee7125");
assert.equal(lfm.filename, "LFM2.5-1.2B-Instruct-QAD-Q4_0.gguf"); assert.equal(lfm.expectedSize, 695755488);
assert.equal(lfm.sha256, "bb741ebb106d543e9de114b843a3d3d73d51c74b5801e69da2abde821a0cb3e1"); assert.equal(lfm.license, "LFM1.0");
assert.equal(fs.existsSync(path.join(root, "android/third_party/needle3/android-arm64/libneedle.a")), true);
assert.equal(fs.existsSync(path.join(root, "android/third_party/needle3/android-arm64/needle.h")), true);
const header = fs.readFileSync(path.join(root, "android/third_party/needle3/android-arm64/needle.h"), "utf8");
for (const symbol of ["needle_load", "needle_init", "needle_complete", "needle_embed", "needle_reset", "needle_last_error"]) assert(header.includes(symbol), `missing official symbol ${symbol}`);
const cmake = fs.readFileSync(path.join(root, "android/app/src/main/cpp/functiongemma/CMakeLists.txt"), "utf8");
assert(cmake.includes("needle3"), "Needle JNI must be included by Android CMake");
const kotlin = fs.readFileSync(path.join(root, "android/app/src/main/java/br/com/ne3d/erp/ai/NeedleProvider.kt"), "utf8");
assert(kotlin.includes("newSingleThreadExecutor"), "Needle provider must serialize calls");
assert(kotlin.includes("cancelSupported", "false"), "native cancellation must not be invented");
assert(kotlin.includes("NEEDLE_IMPORT_CONTENT_URI_REQUIRED"), "manual import must reject arbitrary file paths");
const shadow = fs.readFileSync(path.join(root, "src/ai/needle-shadow-provider.js"), "utf8");
assert(shadow.includes("slice(0, 3)"), "shadow payload must cap candidates at top 3");
assert(shadow.includes("INVALID_TOOL") === false, "invalid tool is represented, never executed");
assert(shadow.includes("function_calls"), "Needle's official function_calls envelope must be parsed");
assert(shadow.includes("inventedIdFields"), "unresolved model-provided IDs must be recorded");
console.log("Needle Lote 4 static contract: PASS");
