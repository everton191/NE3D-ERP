const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('app.js','utf8');
const start = source.indexOf('function mesclarConfiguracaoBackup(');
const context = vm.createContext({});
vm.runInContext(source.slice(start,source.indexOf('\nfunction aplicarBackup(',start)),context);
const current = {theme:'dark',accentColor:'#123456',appearanceSettings:{theme_mode:'dark'},customizationSyncPending:true,uiScale:90,businessName:'Local'};
const stale = {theme:'light',accentColor:'#ffffff',appearanceSettings:{theme_mode:'light'},customizationSyncPending:false,uiScale:120,businessName:'Remota'};
const before = JSON.stringify(current);
const merged = context.mesclarConfiguracaoBackup(current,stale,true);
for (const key of ['theme','accentColor','appearanceSettings','customizationSyncPending','uiScale']) assert.equal(merged[key],current[key]);
assert.equal(merged.businessName,'Remota');
assert.equal(JSON.stringify(current),before);
assert.equal(context.mesclarConfiguracaoBackup(current,stale,false).theme,'light');
assert(!Object.hasOwn(context.mesclarConfiguracaoBackup({},stale,true),'theme'));
const currentPrefs = {autoplay:false,cardOrder:['b','a'],visibleCardIds:['b','a'],autoplayInterval:9000};
const stalePrefs = {autoplay:true,cardOrder:['a','b'],visibleCardIds:['a','b'],autoplayInterval:15000};
const withPrefs = {...current,homeCarouselPreferences:currentPrefs};
const staleWithPrefs = {...stale,homeCarouselPreferences:stalePrefs};
assert.equal(context.mesclarConfiguracaoBackup(withPrefs,staleWithPrefs,true).homeCarouselPreferences,currentPrefs);
assert.equal(context.mesclarConfiguracaoBackup(withPrefs,staleWithPrefs,false).homeCarouselPreferences,stalePrefs);
assert.equal(context.mesclarConfiguracaoBackup(current,staleWithPrefs,true).homeCarouselPreferences,stalePrefs);
assert(source.includes('modo === "mesclar" || opcoes.preservarVisual === true'));
assert(source.includes('aplicarBackup(remoto, "substituir", { preservarVisual: true })'));
console.log('Theme backup authority passed: automatic merge preserves visuals, pending flag and local carousel preferences; manual restoration and nonvisual data retained.');
