"use strict";
const assert = require("assert");
const fs = require("fs");
const path = require("path");
const root = path.resolve(__dirname, "..");
const read = (relative) => fs.readFileSync(path.join(root, relative), "utf8");

const manifest = JSON.parse(read("models/models-manifest.v1.json"));
const balanced = manifest.artifacts.find((item) => item.modelId === "gemma-4-e2b-it");
assert.equal(manifest.manifestVersion, 1);
assert.equal(manifest.artifacts.length, 3);
assert.equal(balanced.downloadBytes, 2588147712);
assert.equal(balanced.sha256, "181938105e0eefd105961417e8da75903eacda102c4fce9ce90f50b97139a63c");
assert.match(balanced.artifactUrl, /resolve\/[a-f0-9]{40}\//);
assert.doesNotMatch(balanced.artifactUrl, /resolve\/main\//);

const plugin = read("android/app/src/main/java/br/com/ne3d/erp/SimplificaLocalAiPlugin.kt");
const manager = read("android/app/src/main/java/br/com/ne3d/erp/ai/ModelArtifactManager.kt");
const worker = read("android/app/src/main/java/br/com/ne3d/erp/ai/LocalModelDownloadWorker.kt");
const engine = read("android/app/src/main/java/br/com/ne3d/erp/ai/LocalInferenceEngine.kt");
const profiler = read("android/app/src/main/java/br/com/ne3d/erp/ai/DeviceCapabilityProfiler.kt");
const benchmark = read("android/app/src/main/java/br/com/ne3d/erp/ai/ModelHealthBenchmark.kt");
const app = read("app.js");

assert.doesNotMatch(plugin, /override fun load|ensure_model|content:\/\//, "O plugin não pode iniciar download no carregamento nem usar provider externo");
assert.match(plugin, /fun installModel/);
assert.match(plugin, /fun deleteModel/);
assert.match(plugin, /fun setEnabled/);
assert.match(manager, /getBoolean\(KEY_ENABLED, false\)/, "A IA deve iniciar desligada");
assert.match(manager, /isReady[\s\S]*KEY_VERIFIED_VERSION[\s\S]*KEY_VERIFIED_SHA/);
assert.match(manager, /KEY_WORK_TOKEN[\s\S]*UUID\.randomUUID\(\)/);
assert.match(manager, /verifiedVersionKey[\s\S]*verifiedShaKey/);
assert.match(manager, /fun cancel[\s\S]*remove\(KEY_WORK_TOKEN\)\.commit\(\)/);
assert.match(worker, /isStopped \|\| !ModelArtifactManager\.isActiveWork/);
assert.match(worker, /updateProgressFromWorker/);
assert.match(worker, /setRequestProperty\("Range"/);
assert.match(worker, /sha256\(temporary\)/);
assert.match(worker, /StandardCopyOption\.ATOMIC_MOVE/);
assert.match(engine, /Backend\.GPU\(\)[\s\S]*Backend\.CPU\(\)/);
assert.match(engine, /visionBackend = if \(vision\) Backend\.GPU\(\)/);
assert.match(engine, /Content\.ImageFile\(imagePath\)/);
assert.match(plugin, /imageBase64[\s\S]*imageMimeType[\s\S]*assistant-images[\s\S]*temporaryImage\?\.delete\(\)/);
assert.match(plugin, /payload.*answer.*nunca deixe answer vazio/i);
assert.match(profiler, /memoryClass[\s\S]*largeMemoryClass[\s\S]*SUPPORTED_ABIS[\s\S]*availableBytes/);
assert.match(profiler, /LiteRT-LM 0\.15\.0[\s\S]*GPU_FIRST_CPU_FALLBACK/);
assert.match(benchmark, /enum class ModelHealth \{ NOT_TESTED, READY, SLOW, UNSTABLE, FAILED \}/);
assert.match(benchmark, /initializationMs[\s\S]*estimatedTokensPerSecond[\s\S]*setRequiresBatteryNotLow/);
assert.match(plugin, /fun profileDevice[\s\S]*fun benchmarkModel/);
assert.match(plugin, /installed[\s\S]*compatible/);
assert.match(app, /Baixar modelo de IA\?[\s\S]*Agora não/);
assert.match(app, /Cancelar download/);
assert.match(app, /baixarModeloAssistenteIa[\s\S]*state: "DOWNLOADING"[\s\S]*assistenteIaConfigPollTimer/);
assert.match(app, /cancelarDownloadAssistenteIa[\s\S]*state: "NOT_INSTALLED"[\s\S]*provider\.cancelDownload/);
assert.match(app, /Remover e liberar/);
console.log("Lifecycle independente dos modelos Android validado por contrato.");
